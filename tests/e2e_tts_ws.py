"""Live end-to-end latency over the real websocket (uses Soniox; costs a few cents).
Speech is generated by the server's own TTS ('speak'), then streamed back as mic audio in real time.
Run: URL=wss://your-domain.example/ws ESCUCHA_CODE=... python3 tests/e2e_tts_ws.py"""
import asyncio, base64, json, os, time, urllib.parse
import aiohttp
URL = (__import__("sys").argv[1:] or [os.environ.get("URL", "ws://127.0.0.1:8790/ws")])[0]
CODE = os.environ.get("ESCUCHA_CODE", os.environ.get("ESCUCHA_PASSCODE", ""))
CASES = [("es", "Buenos días, ¿a qué hora es la cita con el médico mañana?"),
         ("zh", "你好，我想预约下周二上午看医生。")]

async def tts(s, ws, text):
    await ws.send_json({"type": "speak", "text": text, "voice": "Lucia", "id": "x"})
    pcm = b""
    async for m in ws:
        d = json.loads(m.data)
        if d.get("type") == "tts":
            if d.get("audio"): pcm += base64.b64decode(d["audio"])
            if d.get("end"): return pcm

async def main():
    url = URL + "?code=" + urllib.parse.quote(CODE)
    async with aiohttp.ClientSession() as s:
        async with s.ws_connect(url) as ws:   # wrong code must be refused
            pass
        async with s.ws_connect(URL + "?code=wrong") as bad:
            await bad.receive(timeout=5); assert bad.close_code == 4401, bad.close_code
        print("passcode check OK (wrong code -> 4401)")
        async with s.ws_connect(url) as ws:
            audios = [(lang, text, await tts(s, ws, text)) for lang, text in CASES]
            await ws.send_json({"type": "start"})
            for lang, text, pcm in audios:
                pcm += b"\0" * 48000 * 2  # 2 s of silence after speech
                chunk = 3840  # 80 ms
                end_speech = None
                async def feed():
                    nonlocal end_speech
                    speech_len = len(pcm) - 96000
                    for i in range(0, len(pcm), chunk):
                        await ws.send_bytes(pcm[i:i + chunk])
                        if end_speech is None and i + chunk >= speech_len: end_speech = time.time()
                        await asyncio.sleep(0.08)
                    for _ in range(60):  # keep the stream alive with silence
                        await ws.send_bytes(b"\0" * chunk); await asyncio.sleep(0.08)
                ft = asyncio.create_task(feed())
                first_tr = done_tr = None; tr = ""; src = ""
                while True:
                    try: m = await ws.receive(timeout=12)
                    except asyncio.TimeoutError: break
                    if m.type != aiohttp.WSMsgType.TEXT: break
                    d = json.loads(m.data)
                    if d["type"] == "final": src = d["es"]
                    if d["type"] == "translation" and d.get("zh") and src:
                        tr = d["zh"]; now = time.time()
                        if end_speech and first_tr is None: first_tr = now
                        if d.get("done"): done_tr = now; break
                ft.cancel()
                lat = lambda t: f"{t - end_speech:+.2f}s" if t and end_speech else "n/a"
                print(f"[{lang}->{'zh' if lang=='es' else 'es'}] heard: {src!r}\n   translation: {tr!r}\n   latency after end of speech: first {lat(first_tr)}, complete {lat(done_tr)}")
                await asyncio.sleep(1)

asyncio.run(main())
